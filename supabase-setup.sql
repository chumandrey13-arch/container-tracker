-- Выполнить один раз в Supabase: SQL Editor → New query → Run.
create table if not exists public.tracker_snapshots (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  uploaded_by uuid not null references auth.users(id) on delete restrict,
  journal_name text not null,
  report_names jsonb not null default '[]'::jsonb,
  source_folder text not null,
  records jsonb not null,
  counts jsonb not null default '{}'::jsonb
);

alter table public.tracker_snapshots enable row level security;
revoke all on public.tracker_snapshots from anon;
grant select, insert on public.tracker_snapshots to authenticated;
grant usage, select on sequence public.tracker_snapshots_id_seq to authenticated;

drop policy if exists "signed-in team can read snapshots" on public.tracker_snapshots;
create policy "signed-in team can read snapshots"
  on public.tracker_snapshots for select to authenticated using (true);
drop policy if exists "signed-in team can insert snapshots" on public.tracker_snapshots;
create policy "signed-in team can insert snapshots"
  on public.tracker_snapshots for insert to authenticated with check (auth.uid() = uploaded_by);

-- Private bucket for the original Excel files. No public download access.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('container-source-files', 'container-source-files', false, 52428800,
  array['application/vnd.openxmlformats-officedocument.spreadsheetml.sheet','application/vnd.ms-excel','application/vnd.ms-excel.sheet.macroEnabled.12','application/octet-stream'])
on conflict (id) do nothing;

drop policy if exists "team can upload source files" on storage.objects;
create policy "team can upload source files" on storage.objects
 for insert to authenticated with check (bucket_id = 'container-source-files');
drop policy if exists "team can read source files" on storage.objects;
create policy "team can read source files" on storage.objects
 for select to authenticated using (bucket_id = 'container-source-files');
drop policy if exists "team can update source files" on storage.objects;
create policy "team can update source files" on storage.objects
 for update to authenticated using (bucket_id = 'container-source-files') with check (bucket_id = 'container-source-files');
